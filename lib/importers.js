/**
 * Fetch a list of chapter pages and append them to a book.
 *
 * The lessons from the first real crawl are baked in here, because they are
 * what makes a 300-chapter book possible without a ban:
 *
 * - requests are paced against a module-level clock, so two tool calls in a
 *   row cannot burst past the site's per-minute quota;
 * - a rate-limit answer (HTTP 400/403/429) gets exactly one retry after a
 *   long cooldown, and the batch then stops instead of hammering;
 * - chapters already present in the book are skipped by title, so re-running
 *   a partially failed batch is idempotent and never duplicates or reorders;
 * - stopping returns the untouched tail as `remaining`, so the caller can
 *   continue from the first missing chapter.
 */
import fs from 'node:fs/promises'
import path from 'node:path'
import { readEpub } from './epub.js'
import { extractMainText } from './html.js'
import { normalizeBody, splitChapters } from './text.js'
import { fetchResource, readCachedChapter, readCachedToc } from './sources.js'

/** Minimum gap between two chapter requests, shared across tool calls. */
const DEFAULT_GAP_MS = 5000
/** How long to sit out when the site answers with a rate-limit status. */
const DEFAULT_COOLDOWN_MS = 70000
/** Consecutive rate-limit answers after which the batch gives up. */
const MAX_RATE_LIMIT_HITS = 2

const RATE_LIMIT = /\b(400|403|429|503)\b/

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))

let lastRequestAt = 0

const appendLocks = new Map()

/** Serialise appends per book so concurrent batches cannot drop chapters. */
async function withBookLock(bookId, work) {
  const previous = appendLocks.get(bookId) ?? Promise.resolve()
  const run = previous.then(work, work)
  const guard = run.catch(() => {})
  appendLocks.set(bookId, guard)
  try {
    return await run
  } finally {
    if (appendLocks.get(bookId) === guard) appendLocks.delete(bookId)
  }
}

function normalizeTitle(value) {
  return String(value ?? '').replace(/\s+/g, '').trim()
}

function titleOf(entry) {
  return typeof entry === 'object' && entry ? String(entry.title ?? '') : ''
}

function urlOf(entry) {
  return typeof entry === 'string' ? entry : entry?.url
}

function decodeBookBuffer(buffer) {
  const utf8 = new TextDecoder('utf-8', { fatal: false }).decode(buffer)
  const broken = (utf8.match(/\uFFFD/g) ?? []).length
  if (broken > 0 && broken / Math.max(1, utf8.length) > 0.002) {
    try {
      return new TextDecoder('gb18030', { fatal: false }).decode(buffer)
    } catch {
      return utf8
    }
  }
  return utf8
}

function baseName(filePath) {
  return path.basename(filePath).replace(/\.(txt|epub|html?|md)$/i, '')
}

/** Slice out one JS array literal, respecting strings and escapes. */
function sliceArrayLiteral(source, start) {
  let depth = 0
  let inString = false
  let escaped = false
  for (let i = start; i < source.length; i += 1) {
    const ch = source[i]
    if (inString) {
      if (escaped) escaped = false
      else if (ch === '\\') escaped = true
      else if (ch === '"') inString = false
      continue
    }
    if (ch === '"') {
      inString = true
      continue
    }
    if (ch === '[') depth += 1
    else if (ch === ']') {
      depth -= 1
      if (depth === 0) return source.slice(start, i + 1)
    }
  }
  return null
}

/**
 * Single-file reader pages generated by this project's build script embed the
 * whole book as `var DATA=[{"t":title,"b":body},…]`. Reading that beats
 * re-splitting the rendered page: chapter boundaries stay exactly as built.
 */
export function readReaderData(html) {
  const marker = /var\s+DATA\s*=\s*/.exec(html)
  if (marker === null) return null
  const start = html.indexOf('[', marker.index + marker[0].length)
  if (start === -1) return null
  const literal = sliceArrayLiteral(html, start)
  if (literal === null) return null
  try {
    const rows = JSON.parse(literal)
    if (!Array.isArray(rows) || rows.length === 0) return null
    const chapters = []
    for (const row of rows) {
      if (!row || typeof row.b !== 'string') continue
      const text = normalizeBody(row.b)
      if (text === '') continue
      chapters.push({ title: String(row.t ?? `第 ${chapters.length + 1} 章`), text })
    }
    return chapters.length === 0 ? null : chapters
  } catch {
    return null
  }
}

function htmlTitle(html) {
  const match = /<title[^>]*>([\s\S]*?)<\/title>/i.exec(html)
  return match === null ? '' : normalizeBody(match[1]).replace(/\s+/g, ' ').slice(0, 120)
}

/** Chapters from a saved HTML page: embedded data first, readable text second. */
export function chaptersFromHtml(html) {
  const embedded = readReaderData(html)
  if (embedded !== null) return { title: htmlTitle(html), chapters: embedded }
  return { title: htmlTitle(html), chapters: splitChapters(extractMainText(html)) }
}

export async function importText(library, { title, author, text, source = 'text' }) {
  const chapters = splitChapters(text)
  if (chapters.length === 0) throw new Error('正文为空，没有可导入的章节')
  const book = await library.create({ title: title || '未命名', author, source, chapters })
  return { book, chapters: chapters.length }
}

export async function importFile(library, filePath, { title, author } = {}) {
  const stat = await fs.stat(filePath)
  const buffer = await fs.readFile(filePath)
  const isEpub = /\.epub$/i.test(filePath)
  if (isEpub) {
    const parsed = readEpub(buffer)
    if (parsed.chapters.length === 0) throw new Error('EPUB 里没有解析出章节')
    const book = await library.create({
      title: title || parsed.title || baseName(filePath),
      author: author || parsed.author,
      source: 'epub',
      chapters: parsed.chapters,
    })
    return { book, chapters: parsed.chapters.length, bytes: stat.size }
  }
  if (/\.x?html?$/i.test(filePath)) {
    const parsed = chaptersFromHtml(decodeBookBuffer(buffer))
    if (parsed.chapters.length === 0) throw new Error('网页里没有解析出章节')
    const book = await library.create({
      title: title || parsed.title || baseName(filePath),
      author,
      source: 'html',
      chapters: parsed.chapters,
    })
    return { book, chapters: parsed.chapters.length, bytes: stat.size }
  }
  const text = decodeBookBuffer(buffer)
  const chapters = splitChapters(text)
  if (chapters.length === 0) throw new Error('文件里没有可识别的正文')
  const book = await library.create({
    title: title || baseName(filePath),
    author,
    source: 'txt',
    chapters,
  })
  return { book, chapters: chapters.length, bytes: stat.size }
}

export async function importUrl(library, url, { title, author, selector } = {}) {
  const resource = await fetchResource(url, { as: 'buffer' })
  const contentType = (resource.contentType || '').toLowerCase()
  if (contentType.includes('epub') || /\.epub(\?|$)/i.test(url)) {
    const parsed = readEpub(resource.buffer)
    if (parsed.chapters.length === 0) throw new Error('EPUB 里没有解析出章节')
    const book = await library.create({
      title: title || parsed.title || '未命名',
      author: author || parsed.author,
      source: 'epub-url',
      chapters: parsed.chapters,
    })
    return { book, chapters: parsed.chapters.length }
  }
  if (contentType.includes('octet-stream')) {
    throw new Error('该地址返回二进制文件；请确认是 .epub，或先下载到本地再用文件导入')
  }
  const { text } = await fetchResource(url, { as: 'text' })
  const body = contentType.includes('html') || /<html|<body|<div/i.test(text)
    ? extractMainText(text, selector)
    : text
  const chapters = splitChapters(body)
  if (chapters.length === 0) throw new Error('页面里没有提取到正文；可以用 selector 指定正文容器')
  const book = await library.create({
    title: title || chapters[0].title || '未命名',
    author,
    source: 'url',
    chapters,
  })
  return { book, chapters: chapters.length }
}

/**
 * Copy a book that dsh-novel already downloaded.
 * Chapters never fetched by that plugin stay empty and are reported back.
 */
export async function importNovelCache(library, { bookKey, sourceId, title, author }) {
  const toc = await readCachedToc(sourceId, bookKey)
  if (toc === null) throw new Error('没有找到这本书的目录缓存（先用 dsh-novel 取一次目录）')

  // Importing the same book twice must refresh it, never clone it: a clone
  // would strand the reading progress and the `cached` report of the original.
  const existing = await findBookByKey(library, bookKey, sourceId)
  const book = existing ?? await library.create({
    title: title || '未命名',
    author,
    source: 'dsh-novel',
    chapters: [],
  })
  if (!existing && title) book.title = title.slice(0, 120)
  book.bookKey = bookKey
  book.sourceId = sourceId

  const chapterFileOf = (index) => path.join(library.bookDir(book.id), 'ch', `${String(index).padStart(4, '0')}.txt`)
  await fs.mkdir(path.join(library.bookDir(book.id), 'ch'), { recursive: true })
  let filled = 0
  for (let index = 0; index < toc.length; index += 1) {
    if (index >= book.chapters.length) {
      book.chapters.push({ title: String(toc[index].name || `第 ${index + 1} 章`).slice(0, 120) })
    }
    if (await hasText(chapterFileOf(index))) continue
    const cached = await readCachedChapter(sourceId, bookKey, index)
    if (cached === null) continue
    await fs.writeFile(chapterFileOf(index), cached, 'utf8')
    filled += 1
  }
  let missing = 0
  for (let index = 0; index < toc.length; index += 1) {
    if (!(await hasText(chapterFileOf(index)))) missing += 1
  }
  book.cached = { missing, total: toc.length }
  book.updatedAt = new Date().toISOString()
  await library.writeMeta(book)
  return { book, chapters: toc.length, missing, filled, merged: existing !== null }
}

/** A chapter file that exists and is not empty. */
async function hasText(file) {
  try {
    const stat = await fs.stat(file)
    return stat.size > 0
  } catch {
    return false
  }
}

/** Locate an already imported dsh-novel book by its identity. */
async function findBookByKey(library, bookKey, sourceId) {
  for (const entry of await library.list()) {
    const meta = await library.readMeta(entry.id)
    if (meta === null) continue
    if (meta.bookKey === bookKey && (meta.sourceId ?? '') === (sourceId ?? '')) return meta
  }
  return null
}

/** One paced request: never two chapters closer than the shared gap. */
async function pacedChapter(url, gapMs) {
  const wait = gapMs - (Date.now() - lastRequestAt)
  if (wait > 0) await sleep(wait)
  try {
    return await fetchResource(url, { as: 'text' })
  } finally {
    lastRequestAt = Date.now()
  }
}

/**
 * Fetch a list of chapter pages and append them to a book.
 * Used by the agent after it has discovered the chapter URLs of a site.
 */
export async function downloadChapters(library, {
  bookId,
  title,
  author,
  chapters,
  selector,
  delayMs = DEFAULT_GAP_MS,
  cooldownMs = DEFAULT_COOLDOWN_MS,
} = {}) {
  const gapMs = Math.max(0, Number(delayMs) || 0)
  let book = null
  if (bookId) {
    book = await library.readMeta(bookId)
    // A typo, or a deleted book, must fail loudly: silently creating a second
    // copy would strand the reading progress of the original.
    if (book === null) throw new Error(`书不存在：${bookId}（要新建一本就别传 bookId）`)
  }

  // Skip what the book already has: a retry must never duplicate or reorder.
  const have = new Set((book?.chapters ?? []).map((chapter) => normalizeTitle(chapter.title)))
  const wanted = []
  const skipped = []
  for (const entry of chapters) {
    const url = urlOf(entry)
    if (!url) continue
    const knownTitle = titleOf(entry)
    if (knownTitle !== '' && have.has(normalizeTitle(knownTitle))) {
      skipped.push(url)
      continue
    }
    wanted.push(entry)
  }

  const failures = []
  /** Chapters that did NOT reach the book, in reading order. */
  const unsaved = []
  let rateLimitHits = 0
  let added = 0

  const attempt = async (url) => {
    const { text } = await pacedChapter(url, gapMs)
    const body = normalizeBody(extractMainText(text, selector))
    if (body.length < 30) throw new Error('正文过短，可能被站点拦截或选择器不对')
    return { body, pageTitle: guessTitle(text) }
  }

  /** Write one chapter now, so an interrupted batch keeps what it fetched. */
  const persist = async (chapter) => {
    if (book === null) {
      book = await library.create({
        title: title || chapter.title || '未命名',
        author,
        source: 'download',
        chapters: [chapter],
      })
      return
    }
    const dir = path.join(library.bookDir(book.id), 'ch')
    await fs.mkdir(dir, { recursive: true })
    const index = book.chapters.length
    await fs.writeFile(path.join(dir, `${String(index).padStart(4, '0')}.txt`), chapter.text, 'utf8')
    book.chapters.push({ title: String(chapter.title).slice(0, 120) })
    book.updatedAt = new Date().toISOString()
    await library.writeMeta(book)
  }

  const nextTitle = () => `第 ${(book?.chapters.length ?? added) + 1} 章`

  const run = async () => {
    // Another batch may have appended while this one waited for the lock.
    if (book !== null) {
      const fresh = await library.readMeta(book.id)
      if (fresh === null) throw new Error(`书不存在：${book.id}`)
      book = fresh
    }
    for (let i = 0; i < wanted.length; i += 1) {
      const entry = wanted[i]
      const url = urlOf(entry)
      const fallback = titleOf(entry) || nextTitle()
      try {
        const { body, pageTitle } = await attempt(url)
        await persist({ title: titleOf(entry) || pageTitle || fallback, text: body })
        added += 1
        rateLimitHits = 0
        continue
      } catch (error) {
        const message = error instanceof Error ? error.message : String(error)
        if (!RATE_LIMIT.test(message)) {
          failures.push({ url, reason: message })
          unsaved.push(url)
          continue
        }
        // Sit out the site's cooldown once, then try the same chapter again.
        await sleep(cooldownMs)
        try {
          const { body, pageTitle } = await attempt(url)
          await persist({ title: titleOf(entry) || pageTitle || fallback, text: body })
          added += 1
          rateLimitHits = 0
        } catch (retryError) {
          rateLimitHits += 1
          failures.push({
            url,
            reason: (retryError instanceof Error ? retryError.message : String(retryError))
              + `（冷却 ${Math.round(cooldownMs / 1000)}s 后仍失败）`,
          })
          unsaved.push(url)
          if (rateLimitHits >= MAX_RATE_LIMIT_HITS) {
            // Stop before the site bans us, but keep the whole tail — the
            // chapter that just failed included — so one more call finishes it.
            for (let j = i + 1; j < wanted.length; j += 1) unsaved.push(urlOf(wanted[j]))
            break
          }
        }
      }
    }
  }

  // One writer per book: a second batch queues instead of interleaving.
  if (book !== null) await withBookLock(book.id, run)
  else await run()

  return {
    book,
    added,
    failures,
    remaining: unsaved,
    skipped: skipped.length,
  }
}

function guessTitle(html) {
  const match = /<title[^>]*>([\s\S]*?)<\/title>/i.exec(html)
  if (match === null) return ''
  return normalizeBody(match[1]).replace(/\s+/g, ' ').trim().slice(0, 80)
}
